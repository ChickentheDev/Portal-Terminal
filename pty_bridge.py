#!/usr/bin/env python3
"""
Tiny pty bridge used by the built-in terminal.

usage: pty_bridge.py SHELL CWD COLS ROWS

- stdin  -> keystrokes for the shell
- stdout <- everything the shell prints
- fd 3   -> control lines, e.g. "R <cols> <rows>" to resize

It exists so the app can offer a real terminal (colors, vim, htop, ...)
without compiling a native Node module, which is painful on SteamOS.
"""
import atexit
import fcntl
import os
import pty
import select
import shlex
import shutil
import signal
import struct
import sys
import tempfile
import termios


def set_size(fd, cols, rows):
    try:
        fcntl.ioctl(fd, termios.TIOCSWINSZ, struct.pack("HHHH", rows, cols, 0, 0))
    except OSError:
        pass


def write_all(fd, data):
    while data:
        n = os.write(fd, data)
        data = data[n:]


def fish_quote(p):
    # Single-quoted fish string: backslash escapes the next char.
    return "'" + p.replace("\\", "\\\\").replace("'", "\\'") + "'"


def sh_dquote(p):
    # Double-quoted POSIX string for the generated .zshrc.
    return '"' + p.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("`", "\\`") + '"'


def shell_launch(shell):
    """Return (argv, zdotdir-or-None) for the shell.

    With PORTAL_SHELL_INTEGRATION=1 and PORTAL_INTEGRATION_DIR set, bash,
    zsh and fish get their Portal integration injected WITHOUT touching the
    user's dotfiles. Anything else (or a missing script) launches exactly
    as before, and the app falls back to the keystroke block tracker.
    """
    argv = [shell, "-i"]
    if os.environ.get("PORTAL_SHELL_INTEGRATION") != "1":
        return argv, None
    idir = os.environ.get("PORTAL_INTEGRATION_DIR") or ""
    if not idir or not os.path.isdir(idir):
        return argv, None
    base = os.path.basename(shell)
    if base == "bash":
        init = os.path.join(idir, "bash-init.sh")
        if os.path.isfile(init):
            argv = [shell, "--rcfile", init, "-i"]
    elif base == "zsh":
        script = os.path.join(idir, "zsh.sh")
        if os.path.isfile(script):
            # zsh reads ALL its startup files from $ZDOTDIR. Point it at a
            # temp dir that symlinks the user's real files (so .zshenv /
            # .zprofile / .zlogin are not skipped) plus a generated .zshrc
            # that sources the user's .zshrc and then the integration.
            zdot = tempfile.mkdtemp(prefix="portal-zdot-")
            home = os.path.expanduser("~")
            for dot in (".zshenv", ".zprofile", ".zlogin", ".zlogout"):
                src = os.path.join(home, dot)
                if os.path.exists(src):
                    try:
                        os.symlink(src, os.path.join(zdot, dot))
                    except OSError:
                        pass
            with open(os.path.join(zdot, ".zshrc"), "w") as f:
                f.write("# Generated by Portal Terminal — do not edit. Removed when the shell exits.\n")
                f.write('[ -f "$HOME/.zshrc" ] && . "$HOME/.zshrc"\n')
                f.write(". " + sh_dquote(os.path.join(idir, "zsh.sh")) + "\n")
            os.environ["ZDOTDIR"] = zdot
            argv = [shell, "-i"]
            return argv, zdot
    elif base == "fish":
        script = os.path.join(idir, "fish.fish")
        if os.path.isfile(script):
            # --init-command runs after the user's config, before the prompt.
            argv = [shell, "-i", "--init-command", "source " + fish_quote(script)]
    return argv, None


def main():
    shell, cwd = sys.argv[1], sys.argv[2]
    cols, rows = int(sys.argv[3]), int(sys.argv[4])

    # Shell integration: build the launch argv (and the temp ZDOTDIR for
    # zsh) BEFORE forking so the child inherits them.
    argv, zdotdir = shell_launch(shell)

    pid, fd = pty.fork()
    if pid == 0:
        try:
            os.chdir(cwd)
        except OSError:
            pass
        os.environ["TERM"] = "xterm-256color"
        os.environ["COLORTERM"] = "truecolor"
        try:
            os.execvp(argv[0], argv)
        except OSError:
            os.execvp("/bin/sh", ["/bin/sh", "-i"])

    set_size(fd, cols, rows)

    # Remove the temp ZDOTDIR when the bridge exits (normal exit and the
    # SIGTERM/SIGHUP handlers both go through sys.exit, which runs atexit).
    if zdotdir:
        atexit.register(lambda: shutil.rmtree(zdotdir, ignore_errors=True))

    def hangup(*_):
        try:
            os.kill(pid, signal.SIGHUP)
        except OSError:
            pass

    signal.signal(signal.SIGTERM, lambda *_: (hangup(), sys.exit(0)))
    signal.signal(signal.SIGHUP, lambda *_: (hangup(), sys.exit(0)))

    watching = [fd, 0, 3]
    ctrl_buf = b""

    try:
        while True:
            try:
                ready, _, _ = select.select(watching, [], [])
            except InterruptedError:
                continue

            if fd in ready:
                try:
                    data = os.read(fd, 65536)
                except OSError:
                    data = b""
                if not data:
                    break
                write_all(1, data)

            if 0 in ready:
                data = os.read(0, 65536)
                if data:
                    write_all(fd, data)
                else:
                    # the app closed our stdin: hang up the shell, keep draining output
                    watching.remove(0)
                    hangup()

            if 3 in ready:
                chunk = os.read(3, 4096)
                if chunk:
                    ctrl_buf += chunk
                    while b"\n" in ctrl_buf:
                        line, ctrl_buf = ctrl_buf.split(b"\n", 1)
                        parts = line.split()
                        if len(parts) == 3 and parts[0] == b"R":
                            try:
                                set_size(fd, int(parts[1]), int(parts[2]))
                            except ValueError:
                                pass
                else:
                    watching.remove(3)
    except (BrokenPipeError, KeyboardInterrupt):
        hangup()

    code = 0
    try:
        _, status = os.waitpid(pid, 0)
        code = os.waitstatus_to_exitcode(status)
    except (ChildProcessError, AttributeError):
        pass
    sys.exit(code if code >= 0 else 1)


if __name__ == "__main__":
    main()
